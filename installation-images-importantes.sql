create table if not exists public.important_images (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 50),
  url text not null unique check (url ~ '^https?://'),
  is_fixed boolean not null default false,
  created_by text not null,
  created_at timestamptz not null default now()
);

alter table public.important_images enable row level security;

drop policy if exists "Lecture publique des images importantes" on public.important_images;
create policy "Lecture publique des images importantes"
on public.important_images for select
to anon, authenticated
using (true);

